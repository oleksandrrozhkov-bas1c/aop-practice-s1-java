package homework.h10;

//https://leetcode.com/problems/reverse-string/submissions/2184808867/

public class T1 {
    public void reverseString(char[] s) {
        int left = 0;
        int right = s.length - 1;

        while (left < right) {
            char temp = s[left];
            s[left] = s[right];
            s[right] = temp;

            left++;
            right--;
        }
    }
}
